def parse_env_file(path: Path) -> Dict[str, str]:
    values: Dict[str, str] = {}
    if not path.exists():
        return values
    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip().strip('"').strip("'")
    return values


def merged_env_values(model_config: Path, eval_env: Path) -> Dict[str, str]:
    merged = parse_env_file(model_config)
    merged.update(parse_env_file(eval_env))
    return merged


def read_target_documents(metadata_path: Path) -> List[str]:
    if not metadata_path.exists():
        return list(DEFAULT_TARGET_DOCUMENTS)
    try:
        data = json.loads(metadata_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return list(DEFAULT_TARGET_DOCUMENTS)
    per_model = data.get("per_model_per_document") or {}
    if not per_model:
        return list(DEFAULT_TARGET_DOCUMENTS)
    first_model = next(iter(per_model.values()))
    if not isinstance(first_model, dict):
        return list(DEFAULT_TARGET_DOCUMENTS)
    docs = [str(doc_id) for doc_id in first_model.keys()]
    return docs or list(DEFAULT_TARGET_DOCUMENTS)


def write_auto_model_config(base_config: Path, output_config: Path) -> Path:
    if not base_config.exists():
        raise FileNotFoundError(f"Base model config not found: {base_config}")
    text = base_config.read_text(encoding="utf-8").rstrip()
    lines = [
        text,
        "",
        "# Auto retrieval/repair mode generated by auto_repair_classifier/run_auto_eval.py",
    ]
    lines.extend(f"{key}={value}" for key, value in AUTO_OVERRIDES.items())
    output_config.parent.mkdir(parents=True, exist_ok=True)
    output_config.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return output_config


